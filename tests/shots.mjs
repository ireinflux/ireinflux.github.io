import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true,
  args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on('console', m => { if (m.type() === 'error' || m.type()==='warning') errs.push(m.type()+': '+m.text()); });
page.on('pageerror', e => errs.push('pageerror: ' + e.message));
await page.goto('file:///workspace/lunar-lander/index.html?failset=historical');
await page.waitForFunction(() => window.__game, null, { timeout: 60000 });
const ev = (f, a) => page.evaluate(f, a);
await ev(()=>{window.__fc=0;const f=()=>{window.__fc++;requestAnimationFrame(f)};requestAnimationFrame(f);});
const frames = async n => { const s = await ev(()=>window.__fc); await page.waitForFunction(t=>window.__fc>=t, s+n, {timeout:120000}); };
await frames(3);
await page.screenshot({ path: 'shot-1-start.png' });
await page.keyboard.press('Space');
await frames(2);
await page.keyboard.down('ArrowDown'); await frames(3); await page.keyboard.up('ArrowDown');
console.log('after takeover', await ev(()=>({auto:__game.S.auto, t:__game.S.t})));
await ev(() => { const g=__game; g.restart(); g.autoland(g.CLEAR.x, g.CLEAR.z); while(g.S.mode==='fly' && g.altitude()>14) g.step(0.25); g.camState.dist=24; g.camState.yaw=Math.PI-0.95; g.camState.pitch=0.2; g.warm(150); });
await frames(3);
console.log(await ev(()=>({alt:__game.altitude(), t:__game.S.t, mode:__game.S.mode})));
await page.screenshot({ path: 'shot-2-descent.png' });
await ev(() => { const g=__game; while(g.S.mode==='fly') g.step(0.25); g.warm(60); const S=g.S; while(S.post.length>1) S.post.shift().fn(); });
await frames(3);
console.log(JSON.stringify(await ev(()=>__game.S.result)));
await page.screenshot({ path: 'shot-3-landed.png' });
await ev(() => { const S=__game.S; while(S.post.length) S.post.shift().fn(); });
await frames(2);
await page.screenshot({ path: 'shot-4-debrief.png' });
await page.keyboard.press('KeyR');
await ev(() => { const g=__game; while(g.S.mode==='fly' && g.altitude()>25) g.step(0.25); g.camState.dist=30; g.warm(120); });
await frames(3);
await page.screenshot({ path: 'shot-extra-boulders.png' });
await ev(() => { const g=__game; g.camState.pitch=0.5; g.camState.dist=24; g.camState.yaw=Math.PI-1.6; while(g.S.mode==='fly') g.step(0.25); g.warm(150); });
await frames(8);
await page.screenshot({ path: 'shot-5-crash.png' });
await ev(() => { const S=__game.S; while(S.post.length) S.post.shift().fn(); });
await frames(2);
console.log(JSON.stringify(await ev(()=>__game.S.result)));
await page.screenshot({ path: 'shot-6-crash-debrief.png' });
await page.keyboard.press('KeyR');
await ev(() => { const g=__game; g.autoland(g.CLEAR.x, g.CLEAR.z); while(g.S.mode==='fly' && g.altitude()>60) g.step(0.25); });
await page.keyboard.press('KeyC'); await frames(10);
console.log('cam', await ev(()=>__game.camState.mode));
await page.screenshot({ path: 'shot-extra-window.png' });
console.log('ERRORS:', errs.length ? errs.join('\n') : 'none');
await browser.close();
